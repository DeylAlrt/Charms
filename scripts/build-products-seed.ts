/**
 * Writes supabase/seed/products.sql (every product, for the Supabase products
 * table) from the lists that are in the code today, and prints where the
 * charm builder's list and the main site's list disagree.
 *
 * The main site's list (src/lib/siteCatalogue.ts) is used for names, prices
 * and sold-out; the builder's list adds which builder category each charm is in.
 *
 * Run: npx esbuild scripts/build-products-seed.ts --bundle --platform=node --alias:@=./src --outfile=<tmp>.js && node <tmp>.js
 */
import fs from 'fs';
import { BUILT_IN_ENTRIES } from '@/components/charmCatalogue';
import { BUILT_IN_WATCHES } from '@/components/charmEditor/watches';
import { SITE_ITEMS } from '@/lib/siteCatalogue';

const sql = (v: string | number | boolean | null) =>
  v === null ? 'null' : typeof v === 'string' ? `'${v.replace(/'/g, "''")}'` : String(v);

const builderByFile = new Map(BUILT_IN_ENTRIES.map(e => [e.file, e]));
const watchByFile = new Map(BUILT_IN_WATCHES.map(w => [w.file, w]));

const category = (section: string) =>
  /watch/i.test(section) ? 'watch' : /keychain/i.test(section) ? 'keychain' : /bracelet/i.test(section) ? 'bracelets' : 'links';

const kind = (section: string, file: string) =>
  file.startsWith('Plain Links/') ? 'plain'
    : file.startsWith('Chain Links/') ? 'twin_chain'
    : /dangling/i.test(section) ? 'dangling'
    : /magnet/i.test(section) ? 'magnet'
    : file.startsWith('Watches/') ? 'watch'
    : /connector|keychain/i.test(section) ? 'other'
    : 'charm';

const metal = (section: string, file: string, label: string) =>
  /gold/i.test(section) || /gold/i.test(file) || /^gold\b/i.test(label) ? 'gold'
    : section.startsWith('Plain Charms — Colors') ? null
    : 'silver';

const differences: string[] = [];
const rows: string[] = [];
const seenFiles = new Set<string>();
const orderInSection = new Map<string, number>();

for (const item of SITE_ITEMS.values()) {
  seenFiles.add(item.file);
  const builder = builderByFile.get(item.file);
  const watch = watchByFile.get(item.file);
  const n = (orderInSection.get(item.section) ?? 0) + 1;
  orderInSection.set(item.section, n);

  if (builder && builder.price !== item.price) differences.push(`PRICE  ${item.section} / ${item.label}: main site ${item.price}, builder ${builder.price} → using main site`);
  if (builder && builder.soldOut !== !!item.soldOut) differences.push(`SOLD OUT  ${item.section} / ${item.label}: main site ${!!item.soldOut}, builder ${builder.soldOut} → using main site`);
  if (watch && watch.price !== item.price) differences.push(`PRICE  ${item.label}: main site ${item.price}, builder watch ${watch.price} → using main site`);
  if (watch && !!watch.soldOut !== !!item.soldOut) differences.push(`SOLD OUT  ${item.label}: main site ${!!item.soldOut}, builder watch ${!!watch.soldOut} → using main site`);

  const builderCategory = builder ? builder.category : watch ? 'Watches' : null;
  rows.push(`(${[
    sql(item.label), sql(category(item.section)), sql(item.section), sql(builderCategory),
    sql(kind(item.section, item.file)), sql(watch ? watch.links.toLowerCase() : metal(item.section, item.file, item.label)),
    sql(item.price.toFixed(2)), sql(item.file), sql(!!item.soldOut), sql(n * 10),
  ].join(', ')})`);
}

for (const entry of BUILT_IN_ENTRIES) {
  if (!seenFiles.has(entry.file)) differences.push(`ONLY IN BUILDER  ${entry.category} / ${entry.displayName} (${entry.file}) → not added`);
}
for (const watch of BUILT_IN_WATCHES) {
  if (!seenFiles.has(watch.file)) differences.push(`ONLY IN BUILDER  watch ${watch.name} → not added`);
}
const onlySite = [...SITE_ITEMS.values()].filter(i => !builderByFile.has(i.file) && !watchByFile.has(i.file));

const out = `-- Every product, generated by scripts/build-products-seed.ts from the lists in the code (${rows.length} products).
-- Run once in the Supabase dashboard → SQL Editor → New query → paste → Run (after the create_tables migration).
-- Running it again updates prices / sold out / names to these values without making duplicates.

insert into public.products (name, category, section, builder_category, kind, metal, price_aed, image_path, sold_out, sort_order)
values
${rows.join(',\n')}
on conflict (section, image_path) do update set
  name = excluded.name,
  category = excluded.category,
  builder_category = excluded.builder_category,
  kind = excluded.kind,
  metal = excluded.metal,
  price_aed = excluded.price_aed,
  sold_out = excluded.sold_out,
  sort_order = excluded.sort_order;
`;
fs.mkdirSync('supabase/seed', { recursive: true });
fs.writeFileSync('supabase/seed/products.sql', out);

console.log(`${rows.length} products written to supabase/seed/products.sql`);
console.log(`Main site only (not in the builder): ${onlySite.length}`);
for (const s of [...new Set(onlySite.map(i => i.section))]) console.log(`   ${s}: ${onlySite.filter(i => i.section === s).map(i => i.label).join(', ')}`);
console.log(`Differences: ${differences.length}`);
for (const d of differences) console.log('   ' + d);
